import json
import os

FILE_NAME = "tasks.json"


def load_tasks():
    """Load saved tasks, or start with an empty list."""
    try:
        with open(FILE_NAME, "r", encoding="utf-8") as file:
            tasks = json.load(file)

        if isinstance(tasks, list):
            return tasks

        print("Saved data is not in the expected format. Starting fresh.")
        return []

    except FileNotFoundError:
        return []
    except json.JSONDecodeError:
        print("The tasks file is invalid. Starting with an empty list.")
        return []


def save_tasks(tasks):
    """Save the current task list to a JSON file."""
    with open(FILE_NAME, "w", encoding="utf-8") as file:
        json.dump(tasks, file, indent=4)


def add_task(tasks):
    """Add a new task with Pending status."""
    title = input("Task title: ").strip()

    if not title:
        print("Task title cannot be empty.")
        return

    task = {"title": title, "done": False}
    tasks.append(task)
    save_tasks(tasks)
    print("Task added.")


def view_tasks(tasks):
    """Display all tasks with their current status."""
    if not tasks:
        print("No tasks found.")
        return

    print("\nYour Tasks:")
    for number, task in enumerate(tasks, start=1):
        if task["done"]:
            status = "Done"
        else:
            status = "Pending"

        print(f"{number}. {task['title']} [{status}]")


def complete_task(tasks):
    """Mark a selected task as completed."""
    if not tasks:
        print("There are no tasks to complete.")
        return

    view_tasks(tasks)

    try:
        number = int(input("Task number to complete: "))

        if number < 1 or number > len(tasks):
            print("Invalid task number.")
            return

        tasks[number - 1]["done"] = True
        save_tasks(tasks)
        print("Task completed.")

    except ValueError:
        print("Please enter a valid whole number.")


def delete_task(tasks):
    """Delete a selected task."""
    if not tasks:
        print("There are no tasks to delete.")
        return

    view_tasks(tasks)

    try:
        number = int(input("Task number to delete: "))

        if number < 1 or number > len(tasks):
            print("Invalid task number.")
            return

        removed_task = tasks.pop(number - 1)
        save_tasks(tasks)
        print(f"Deleted: {removed_task['title']}")

    except ValueError:
        print("Please enter a valid whole number.")


def main():
    """Run the task tracker menu."""
    tasks = load_tasks()

    while True:
        print("\n--- TASK TRACKER ---")
        print("1. Add  2. View  3. Complete  4. Delete  5. Exit")

        choice = input("Choice: ").strip()

        if choice == "1":
            add_task(tasks)
        elif choice == "2":
            view_tasks(tasks)
        elif choice == "3":
            complete_task(tasks)
        elif choice == "4":
            delete_task(tasks)
        elif choice == "5":
            save_tasks(tasks)
            print("Tasks saved. Goodbye!")
            break
        else:
            print("Invalid choice. Please select 1 to 5.")


if __name__ == "__main__":
    main()